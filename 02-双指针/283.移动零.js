/**
 * LeetCode 热题 100 —— 双指针
 *
 * 283. 移动零 (Move Zeroes)
 * 难度: 简单 | 标签: 数组、双指针
 * 链接: https://leetcode.cn/problems/move-zeroes/
 *
 * ───────────────────────────────────────────
 * 题目描述:
 *
 * 给定一个数组 `nums`，编写一个函数将所有 `0` 移动到数组的末尾，同时保持非零元素的相对顺序。
 *
 * 请注意 ，必须在不复制数组的情况下原地对数组进行操作。
 *
 * 示例 1:
 *
 *   输入: nums = [0,1,0,3,12]
 *   输出: [1,3,12,0,0]
 *
 * 示例 2:
 *
 *   输入: nums = [0]
 *   输出: [0]
 *
 * 提示:
 *   - `1 <= nums.length <= 10^4`
 *   - `-2^31 <= nums[i] <= 2^31 - 1`
 *
 * 进阶：你能尽量减少完成的操作次数吗？
 */

/**
 * ───────────────────────────────────────────
 * 解题思路: 快慢双指针，把非零元素交换到前面
 *
 * 1. 慢指针 j 指向"下一个非零元素应该放的位置"，即已整理好的非零区间末尾
 * 2. 快指针 i 从左到右扫描，遇到 nums[i] !== 0 就与 nums[j] 交换，然后 j++
 * 3. 扫描结束后 [0, j) 全是非零元素（相对顺序不变），[j, n) 全是被交换过去的 0
 * 4. i === j 时跳过交换，减少操作次数（对应进阶要求）
 *
 * 复杂度: 时间 O(n)，空间 O(1)，原地修改，返回 void
 */

/**
 * moveZeroes
 * @param {number[]} nums
 * @return {void} 原地修改,不返回值
 */
const moveZeroes = function (nums) {
  // j 指向"下一个非零元素应该放的位置"
  let j = 0;

  for (let i = 0; i < nums.length; i++) {
    if (nums[i] !== 0) {
      // 交换 nums[i] 和 nums[j]（i === j 时无需交换，省一次操作）
      if (i !== j) {
        [nums[i], nums[j]] = [nums[j], nums[i]];
      }
      j++;
    }
  }
};

