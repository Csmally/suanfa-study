/**
 * LeetCode 热题 100 —— 多维动态规划
 *
 * 62. 不同路径 (Unique Paths)
 * 难度: 中等 | 标签: 数学、动态规划、组合数学
 * 链接: https://leetcode.cn/problems/unique-paths/
 *
 * ───────────────────────────────────────────
 * 题目描述:
 *
 * 一个机器人位于一个 `m x n` 网格的左上角 （起始点在下图中标记为 “Start” ）。
 *
 * 机器人每次只能向下或者向右移动一步。机器人试图达到网格的右下角（在下图中标记为 “Finish” ）。
 *
 * 问总共有多少条不同的路径？
 *
 * 示例 1：
 *
 * [图片]
 *
 *   输入：m = 3, n = 7
 *   输出：28
 *
 * 示例 2：
 *
 *   输入：m = 3, n = 2
 *   输出：3
 *   解释：
 *   从左上角开始，总共有 3 条路径可以到达右下角。
 *   1. 向右 -> 向下 -> 向下
 *   2. 向下 -> 向下 -> 向右
 *   3. 向下 -> 向右 -> 向下
 *
 * 示例 3：
 *
 *   输入：m = 7, n = 3
 *   输出：28
 *
 * 示例 4：
 *
 *   输入：m = 3, n = 3
 *   输出：6
 *
 * 提示：
 *   - `1 <= m, n <= 100`
 *   - 题目数据保证答案小于等于 `2 * 10^9`
 */

/**
 * ───────────────────────────────────────────
 * 解题思路: 多维 DP —— 状态从"一个下标"变成"两个下标"
 *
 * ★ 这题是多维 DP 的入门第一题，因为状态定义特别自然 ★
 *
 *   一维 DP（070 爬楼梯、198 打家劫舍）里 dp[i] 只有一个下标，
 *   因为位置只有一个坐标。现在网格式有两个坐标，那就用两个下标。
 *
 * ★ 动态规划的思考模板（四步）★
 *
 *   1. 定义状态:  dp[i][j] = 从左上角走到格子 (i, j) 的路径条数
 *                 （i 是行号、j 是列号，都从 0 开始数）
 *
 *   2. 转移方程:  想走到 (i,j)，【最后一步】只可能从两个方向来 ——
 *                   从上面 (i-1, j) 走下来
 *                   从左边 (i, j-1) 走过来
 *                 （题目只说能往下、往右，所以进入 (i,j) 也只可能来自这两处）
 *                 所以   dp[i][j] = dp[i-1][j] + dp[i][j-1]
 *                 这是"加法原理": 两类来源的路径数直接相加。
 *
 *   3. 初始条件:  ★ 第一行和第一列全部是 1，不是 0 ★
 *                 dp[0][j] = 1 —— 第一行只能一路向右，就 1 条路
 *                 dp[i][0] = 1 —— 第一列只能一路向下，就 1 条路
 *
 *   4. 返回什么:  dp[m-1][n-1]  ← 注意是 0 基下标，右下角是 (m-1, n-1)
 *
 * 拿示例 4  [m=3, n=3] 把整张表填出来:
 *
 *          j=0  j=1  j=2
 *   i=0     1    1    1      ← 第一行初值
 *   i=1     1    2    3      dp[1][1]=1+1=2, dp[1][2]=1+2=3
 *   i=2     1    3    6      dp[2][1]=2+1=3, dp[2][2]=3+3=6
 *           ↑
 *        第一列初值
 *   → dp[2][2] = 6 ✓
 *
 * 示例 1 [m=3, n=7] 填出来是:
 *
 *          j=0  j=1  j=2  j=3  j=4  j=5  j=6
 *   i=0     1    1    1    1    1    1    1
 *   i=1     1    2    3    4    5    6    7
 *   i=2     1    3    6   10   15   21   28
 *   → 28 ✓   （每一格 = 上面 + 左边，像杨辉三角一样铺开）
 *
 * ★ 遍历顺序为什么必须"从上往下、从左往右"★
 *   转移式的两个来源都在左上方，所以只要保证这两个格子【已经算过了】就行。
 *   两层循环 i 从 0 到 m-1、j 从 0 到 n-1 —— 天然满足。
 *
 * ───────────────────────────────────────────
 * 优化: 压成一维数组（滚动数组）
 * ───────────────────────────────────────────
 *
 *   dp[i][*] 只用到 dp[i-1][*]（上一行），用一行数组滚着用就行:
 *
 *     dp[j] = dp[j] + dp[j - 1]
 *             ↑上面      ↑本行左边
 *             （更新前的旧值）  （本轮刚更新过的新值）
 *
 * ★ 这里的 j 要【正序】—— 和 416 分割等和子集的【倒序】正好相反 ★
 *   看着矛盾，其实两题想要的东西不一样:
 *     416: dp[j-x] 要读"还没考虑过当前数字"的旧值 → 倒序，避免一个数字用两次
 *     062: dp[j-1]  要读"本行左边刚算好的"新值 → 正序，正因为它被更新了才用得上
 *   记住判断标准: 【你到底想让右边的格子看见新值还是旧值】。
 *
 * ───────────────────────────────────────────
 * 另一种思路: 组合数学（纯数学，不用 DP）
 * ───────────────────────────────────────────
 *
 *   不管怎么走，从左上到右下都要走 (m-1) 步向下 + (n-1) 步向右，
 *   总步数固定 = m + n - 2。不同的只是【这 m-1 步向下插在哪些位置】。
 *
 *   所以答案就是组合数:  C(m+n-2, m-1)   （等于 C(m+n-2, n-1)，对称）
 *
 *   例: m=3, n=7 → C(8, 2) = 8*7/2 = 28 ✓
 *
 *   代码里用"边乘边除"的写法算组合数:  C(N,k) = ∏ (N-k+i)/i
 *   —— 先乘后除，每一步的结果都是整数，既避免阶乘数值爆炸，
 *      也不会中途产生小数（每一步恰好是 C(N-k+i, i)，本身是整数）。
 *
 *   ★ 一个诚实提醒（下面每个数字都是实测的，不是想当然）★
 *
 *   题目保证"答案 ≤ 2 * 10^9"，而 JS 能精确表示的整数上限是
 *   2^53 ≈ 9 × 10^15 —— 比 2*10^9 大了六个数量级。
 *   在 1..100 的全部 10000 个 (m,n) 组合里实测:
 *     答案 ≤ 2^53 的 3265 个格子 → 二维 DP / 一维 DP / 公式版【全部精确】
 *     答案 >  2^53 的 6735 个格子 → 开始丢精度，两版各有各的丢法:
 *        公式版: 最后的 Number(res) 转换丢的（6553 个对不上）
 *        一二维DP: 加法累加时丢的
 *   所以: 【题目保证范围内的数据，用普通 number 完全没问题】。
 *
 *   但注意约束里 m, n ≤ 100 和"答案 ≤ 2*10^9"其实是矛盾的 ——
 *   m = n = 100 时真答案是 C(198, 99) ≈ 2.28 × 10^58:
 *     精确值(BigInt): 22750883079422934966181954039568885395604168260154104734000
 *     DP 算出来     : 2.2750883079422938e+58   ← 只有前 17 位可信
 *   真要处理这种巨量答案，DP 也得整体换成 BigInt。
 *
 * 易错点:
 *   1. ★ 第一行 / 第一列要初始化成 1 ★ 写成 0 的话整张表全是 0
 *      （只有一种走法: 直着走到底，所以是 1）
 *   2. 返回的是 dp[m-1][n-1]，别写成 dp[m][n]（数组开多大就返回哪一格要分清）
 *   3. 一维压缩时 j 是【正序】，理由见上
 *   4. m = 1 或 n = 1 的退化情况: 只有一条直路，答案 1，别漏了测
 *
 * 复杂度:
 *   二维 DP   —— 时间 O(m*n)，空间 O(m*n)   ← 本文件主解法
 *   一维 DP   —— 时间 O(m*n)，空间 O(n)
 *   组合数学  —— 时间 O(min(m,n))，空间 O(1)
 */

/**
 * uniquePaths
 * 二维 DP: 状态摊在表上，最适合理解 —— 本文件主解法
 * @param {number} m
 * @param {number} n
 * @return {number}
 */
const uniquePaths = function (m, n) {
  // dp[i][j] = 从左上角走到 (i, j) 的路径条数
  const dp = Array.from({ length: m }, () => new Array(n).fill(0));

  // ★ 初值: 第一列全部 1（只能一路往下）
  for (let i = 0; i < m; i++) dp[i][0] = 1;
  // ★ 初值: 第一行全部 1（只能一路往右）
  for (let j = 0; j < n; j++) dp[0][j] = 1;

  // 从上往下、从左往右，保证两个来源都已算好
  for (let i = 1; i < m; i++) {
    for (let j = 1; j < n; j++) {
      dp[i][j] = dp[i - 1][j] + dp[i][j - 1]; // 上面 + 左边
    }
  }

  return dp[m - 1][n - 1];
};

/**
 * uniquePaths1D
 * 一维 DP: 滚动数组，把二维表压成一行，空间 O(n)
 * @param {number} m
 * @param {number} n
 * @return {number}
 */
const uniquePaths1D = function (m, n) {
  // dp[j] 先表示"第一行第 j 格"的路径数，全都是 1
  const dp = new Array(n).fill(1);

  for (let i = 1; i < m; i++) {
    // j 从 1 开始: dp[0] 永远代表第一列，始终是 1，不用动
    for (let j = 1; j < n; j++) {
      // 更新前 dp[j] = 上一行同列（上面那格）
      // 更新后 dp[j-1] = 本行左边那格
      // ★ 这里的 j 是【正序】，正是为了拿到"新鲜的 dp[j-1]"
      dp[j] = dp[j] + dp[j - 1];
    }
  }

  return dp[n - 1];
};

/**
 * uniquePathsMath
 * 组合数学: 答案就是 C(m+n-2, m-1)，O(min(m,n)) 时间、O(1) 空间
 * @param {number} m
 * @param {number} n
 * @return {number}
 */
const uniquePathsMath = function (m, n) {
  const total = m + n - 2; // 总步数
  const k = Math.min(m - 1, n - 1); // C 具有对称性，取小的那个算，循环次数更少

  // ★ 用 BigInt 算 ★
  // 组合数每一步的数学结果确实是整数 C(total-k+i, i)，但用普通 number 时，
  // 中间那个乘积 res * (total-k+i) 会先冲过 2^53（JS 能精确表示整数的上限），
  // 精度一丢，最后再除以 i 甚至会除出 .5 这种小数（真跑过，不是吓唬人）。
  // BigInt 的除法是整除，而这里每步都恰好能整除（1..100 全域 328350 步
  // 实测全部余数为 0），所以【中间计算全程精确】。
  //
  // 唯一还剩的损失: 最后那个 Number(res) —— 答案超过 2^53 时，
  // double 存不下这么多位有效数字。在题目保证的 ≤ 2*10^9 范围内不存在这个问题。
  let res = 1n;
  for (let i = 1; i <= k; i++) {
    // C(total, k) = ∏ (total - k + i) / i
    res = (res * BigInt(total - k + i)) / BigInt(i);
  }

  return Number(res);
};

/**
 * uniquePathsBrute
 * 参照实现: 纯递归枚举每一条路，指数级
 * 同一个格子会被反复走到，只用来给小网格对答案
 * @param {number} m
 * @param {number} n
 * @return {number}
 */
const uniquePathsBrute = function (m, n) {
  const go = (i, j) => {
    if (i === m - 1 && j === n - 1) return 1; // 走到终点了，算作 1 条路

    let count = 0;
    if (i + 1 < m) count += go(i + 1, j); // 往下走
    if (j + 1 < n) count += go(i, j + 1); // 往右走
    return count;
  };

  return go(0, 0);
};

