/**
 * LeetCode 热题 100 —— 多维动态规划
 *
 * 64. 最小路径和 (Minimum Path Sum)
 * 难度: 中等 | 标签: 数组、动态规划、矩阵
 * 链接: https://leetcode.cn/problems/minimum-path-sum/
 *
 * ───────────────────────────────────────────
 * 题目描述:
 *
 * 给定一个包含非负整数的 `m x n` 网格 `grid` ，请找出一条从左上角到右下角的路径，使得路径上的数字总和为最小。
 *
 * 说明：每次只能向下或者向右移动一步。
 *
 * 示例 1：
 *
 * [图片]
 *
 *   输入：grid = [[1,3,1],[1,5,1],[4,2,1]]
 *   输出：7
 *   解释：因为路径 1→3→1→1→1 的总和最小。
 *
 * 示例 2：
 *
 *   输入：grid = [[1,2,3],[4,5,6]]
 *   输出：12
 *
 * 提示：
 *   - `m == grid.length`
 *   - `n == grid[i].length`
 *   - `1 <= m, n <= 200`
 *   - `0 <= grid[i][j] <= 200`
 */

/**
 * ───────────────────────────────────────────
 * 解题思路: 这题就是 062.不同路径 的"换问法"版
 *
 * ★ 先把两题摆在一起看，转移方程几乎一模一样 ★
 *
 *              062. 不同路径                064. 最小路径和
 *   ─────────────────────────────────────────────────────────────
 *   问什么     有多少条路（计数）           哪条路代价最小（最优化）
 *   合并方式   dp[上] + dp[左]             min(dp[上], dp[左]) + grid[i][j]
 *              （加法原理: 两类来源相加）    （取更优的那个，再付本格代价）
 *   第一行/列  全是 1                        前缀和（一路累加）
 *   为什么      第一行只能一路向右            第一行只能一路向右，
 *              所以只有 1 种走法              代价就是这一路加起来
 *   ─────────────────────────────────────────────────────────────
 *
 *   同一个"机器人只能往右/往下走"的场景，一次问"有几条路"、一次问"最便宜的路"。
 *   只要你会 062，这题的骨架就是白送的 —— 要换的只有两处:
 *     (1) 合并两个来源从"相加"改成"取 min"
 *     (2) 边界从"统一填 1"改成"累加前缀和"
 *
 * ★ 动态规划的思考模板（四步）★
 *
 *   1. 定义状态:  dp[i][j] = 从左上角走到格子 (i,j) 的【最小路径和】
 *
 *   2. 转移方程:  走到 (i,j) 的最后一步只可能来自上面或左边，两条来源里
 *                 挑代价更小的那条，再加上本格的数字:
 *                     dp[i][j] = min(dp[i-1][j], dp[i][j-1]) + grid[i][j]
 *
 *   3. 初始条件:  dp[0][0] = grid[0][0]
 *                 ★ 第一行: dp[0][j] = dp[0][j-1] + grid[0][j]（只能从左边来）
 *                 ★ 第一列: dp[i][0] = dp[i-1][0] + grid[i][0]（只能从上边来）
 *                 注意这里和 062 不一样: 062 的边界是"1 种走法"，
 *                 这里没有选择余地，代价就是把一路上的数字全加起来。
 *
 *   4. 返回什么:  dp[m-1][n-1]
 *
 * 拿示例 1  [grid = [[1,3,1],[1,5,1],[4,2,1]]] 把表填出来:
 *
 *   原网格 grid:              填出来的 dp 表:
 *       1  3  1                  1  4  5     ← 第一行前缀和: 1, 1+3, 1+3+1
 *       1  5  1                  2  7  6
 *       4  2  1                  6  8  7
 *                                ↑
 *                            第一列前缀和: 1, 1+1, 1+1+4
 *
 *   dp[1][1] = min(dp[0][1]=4, dp[1][0]=2) + 5 = 7
 *   dp[1][2] = min(dp[0][2]=5, dp[1][1]=7) + 1 = 6
 *   dp[2][1] = min(dp[1][1]=7, dp[2][0]=6) + 2 = 8
 *   dp[2][2] = min(dp[1][2]=6, dp[2][1]=8) + 1 = 7   ✓
 *
 *   对应路径: 1 → 3 → 1 → 1 → 1，也就是 (0,0)→(0,1)→(0,2)→(1,2)→(2,2)
 *
 * ★ 为什么这里能放心取 min —— 最优子结构 ★
 *
 *   设 P 是走到 (i,j) 的一条最优路径，它的最后一步来自上面或左边，
 *   假设来自上面，那么 P 从 (0,0) 到 (i-1,j) 的那一段，
 *   必定【也是走到 (i-1,j) 的最优路径】。证明用反证法:
 *     假如存在一段更便宜的路 P' 能走到 (i-1,j)，
 *     那就把 P 的前半段换成 P'，得到一条走到 (i,j) 且总代价更小的路径，
 *     这和"P 是最优路径"矛盾。
 *   所以想知道 dp[i][j]，只要知道"到上面那格的最小代价"和
 *   "到左边那格的最小代价"，取小的再加本格 —— 够了。
 *   ★ 这就是"最优子结构"的标准论证套路，每道 DP 最优化题都能这么推一遍 ★
 *
 * ───────────────────────────────────────────
 * 优化一: 压成一维数组
 * ───────────────────────────────────────────
 *
 *   dp[i][*] 只用到 dp[i-1][*]，一行滚着用:
 *     dp[j] = min(dp[j], dp[j - 1]) + grid[i][j]
 *             ↑上面      ↑本行左边
 *
 *   j 依然是【正序】—— 因为 dp[j-1] 要的正是"本行左边刚算好的新值"，
 *   而 min 里的 dp[j]（更新前）是"上一行同列的旧值"。两者都要，所以正序。
 *   （和 062 同理；416 那题的倒序是另一回事，那里是为了防止一个数字用两次。）
 *
 * ───────────────────────────────────────────
 * 优化二: 原地修改，额外空间 O(1)
 * ───────────────────────────────────────────
 *
 *   直接把 grid 当 dp 表用: 走过之后，这一格里存的就是"到达它的最小路径和"。
 *   反正 grid[i][j] 的原始值用过一次就再也不会用了。
 *
 *   ★ 副作用提醒 ★ 这会改掉调用方传进来的数组。
 *   LeetCode 上无所谓（判题不检查你的入参），但工程里这么写要小心——
 *   调用者可能还要拿原 grid 做别的事。所以本文件的主解法是【不改输入】的版本，
 *   原地版单独放一个函数，要用的时候自己选。
 *
 * 易错点:
 *   1. ★ 第一行/第一列是【前缀和】，不是 grid 原值 ★
 *      这里没有"两种走法随便挑"的自由，代价就是一路累加（和 062 正好相反）
 *   2. dp[0][0] = grid[0][0] 要单独设 —— 它是唯一没有"来源"的格子
 *   3. ★ 别想着用贪心 ★（每次挑更小的邻居）
 *      看着合理，实测会错。反例（2×3，全是正数）:
 *
 *           1  2  1
 *           1  3  1
 *
 *      三条路各自的代价:
 *         下 → 右 → 右 = 1 + 1 + 3 + 1 = 6     ← 贪心选的
 *         右 → 下 → 右 = 1 + 2 + 3 + 1 = 7
 *         右 → 右 → 下 = 1 + 2 + 1 + 1 = 5     ← 真正最优
 *
 *      在 (0,0) 时，贪心看到"下面那格是 1、右边那格是 2"，就往下走了 ——
 *      可下面紧跟着一个 3 的大坑，而右边虽然第一步贵一点，后面全是 1。
 *      ★ 局部最优 ≠ 全局最优，这正是要 DP 的原因 ★
 *      （随机网格实测: 这种贪心约有 18% 的概率出错，不是罕见情况）
 *   4. 原地版本会改掉入参
 *
 * 复杂度:
 *   二维 DP    —— 时间 O(m*n)，空间 O(m*n)     ← 本文件主解法
 *   一维 DP    —— 时间 O(m*n)，空间 O(n)
 *   原地修改   —— 时间 O(m*n)，空间 O(1)（但会改输入）
 */

/**
 * minPathSum
 * 二维 DP: 状态摊在表上，最适合理解 —— 本文件主解法（不改动入参）
 * @param {number[][]} grid
 * @return {number}
 */
const minPathSum = function (grid) {
  const m = grid.length;
  const n = grid[0].length;

  // dp[i][j] = 从左上角走到 (i,j) 的最小路径和
  const dp = Array.from({ length: m }, () => new Array(n).fill(0));

  dp[0][0] = grid[0][0]; // 起点: 没有来源，代价就是它自己

  // ★ 第一行: 只能从左边一路过来 → 前缀和
  for (let j = 1; j < n; j++) dp[0][j] = dp[0][j - 1] + grid[0][j];

  // ★ 第一列: 只能从上边一路下来 → 前缀和
  for (let i = 1; i < m; i++) dp[i][0] = dp[i - 1][0] + grid[i][0];

  // 从上往下、从左往右，保证两个来源都已算好
  for (let i = 1; i < m; i++) {
    for (let j = 1; j < n; j++) {
      dp[i][j] = Math.min(dp[i - 1][j], dp[i][j - 1]) + grid[i][j];
    }
  }

  return dp[m - 1][n - 1];
};

/**
 * minPathSum1D
 * 一维 DP: 滚动数组，把二维表压成一行，空间 O(n)
 * @param {number[][]} grid
 * @return {number}
 */
const minPathSum1D = function (grid) {
  const m = grid.length;
  const n = grid[0].length;

  // dp[j] 先表示"第一行第 j 格"的最小路径和（前缀和）
  const dp = new Array(n);
  dp[0] = grid[0][0];
  for (let j = 1; j < n; j++) dp[j] = dp[j - 1] + grid[0][j];

  for (let i = 1; i < m; i++) {
    // 第一列: 只能从上面下来，直接累加
    dp[0] += grid[i][0];

    for (let j = 1; j < n; j++) {
      // dp[j] 更新前 = 上面那格（旧值）
      // dp[j-1] 已更新 = 本行左边那格（新值）
      // ★ j 正序，正是为了拿到新鲜的 dp[j-1]
      dp[j] = Math.min(dp[j], dp[j - 1]) + grid[i][j];
    }
  }

  return dp[n - 1];
};

/**
 * minPathSumInPlace
 * 原地修改: 把 grid 本身当 dp 表用，额外空间 O(1)
 * ★ 注意: 会改掉调用方传进来的数组 ★
 * @param {number[][]} grid
 * @return {number}
 */
const minPathSumInPlace = function (grid) {
  const m = grid.length;
  const n = grid[0].length;

  // 从这一步起，grid[i][j] 的含义就变成"到达它的最小路径和"了
  for (let j = 1; j < n; j++) grid[0][j] += grid[0][j - 1];
  for (let i = 1; i < m; i++) grid[i][0] += grid[i - 1][0];

  for (let i = 1; i < m; i++) {
    for (let j = 1; j < n; j++) {
      // 这里的 grid[i][j] 还是原值，用完就没用了，直接覆盖
      grid[i][j] += Math.min(grid[i - 1][j], grid[i][j - 1]);
    }
  }

  return grid[m - 1][n - 1];
};

/**
 * minPathSumBrute
 * 参照实现: 纯递归枚举每一条路，指数级
 * 同一个格子会被反复走到，只用来给小网格对答案
 * @param {number[][]} grid
 * @return {number}
 */
const minPathSumBrute = function (grid) {
  const m = grid.length;
  const n = grid[0].length;

  const go = (i, j) => {
    if (i === m - 1 && j === n - 1) return grid[i][j]; // 到终点了，本格代价

    let best = Infinity;
    if (i + 1 < m) best = Math.min(best, go(i + 1, j)); // 往下走
    if (j + 1 < n) best = Math.min(best, go(i, j + 1)); // 往右走
    return best + grid[i][j]; // 挑更便宜的那条，再加本格代价
  };

  return go(0, 0);
};

/**
 * minPathSumGreedy
 * 反面教材: "每次挑更小的邻居"的贪心，【这是错的】，留在这里当对照
 * 实测随机网格里约 18% 会错，例如 [[1,2,1],[1,3,1]] 会返回 6（正确是 5）
 * @param {number[][]} grid
 * @return {number}
 */
const minPathSumGreedy = function (grid) {
  const m = grid.length;
  const n = grid[0].length;
  let i = 0;
  let j = 0;
  let sum = grid[0][0];

  while (i < m - 1 || j < n - 1) {
    if (i === m - 1) j++; // 到底了，只能往右
    else if (j === n - 1) i++; // 到边了，只能往下
    else if (grid[i][j + 1] <= grid[i + 1][j]) j++; // 右边小就走右边
    else i++; // 否则往下

    sum += grid[i][j];
  }

  return sum;
};

