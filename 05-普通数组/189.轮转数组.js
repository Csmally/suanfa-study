/**
 * LeetCode 热题 100 —— 普通数组
 *
 * 189. 轮转数组 (Rotate Array)
 * 难度: 中等 | 标签: 数组、数学、双指针
 * 链接: https://leetcode.cn/problems/rotate-array/
 *
 * ───────────────────────────────────────────
 * 题目描述:
 *
 * 给定一个整数数组 `nums`，将数组中的元素向右轮转 `k` 个位置，其中 `k` 是非负数。
 *
 * 示例 1:
 *
 *   输入: nums = [1,2,3,4,5,6,7], k = 3
 *   输出: [5,6,7,1,2,3,4]
 *   解释:
 *   向右轮转 1 步: [7,1,2,3,4,5,6]
 *   向右轮转 2 步: [6,7,1,2,3,4,5]
 *   向右轮转 3 步: [5,6,7,1,2,3,4]
 *
 * 示例 2:
 *
 *   输入：nums = [-1,-100,3,99], k = 2
 *   输出：[3,99,-1,-100]
 *   解释:
 *   向右轮转 1 步: [99,-1,-100,3]
 *   向右轮转 2 步: [3,99,-1,-100]
 *
 * 提示：
 *   - `1 <= nums.length <= 10^5`
 *   - `-2^31 <= nums[i] <= 2^31 - 1`
 *   - `0 <= k <= 10^5`
 *
 * 进阶：
 *   - 尽可能想出更多的解决方案，至少有 三种 不同的方法可以解决这个问题。
 *   - 你可以使用空间复杂度为 `O(1)` 的 原地 算法解决这个问题吗？
 */

/**
 * ───────────────────────────────────────────
 * 解题思路: 三次反转（原地 O(1) 空间）
 *
 * 目标: 右转 k 位 = 把后 k 个元素搬到前面，前 n-k 个搬到后面
 *
 * 三次反转法:
 *   1. 反转整个数组 → 后 k 个元素来到前面（顺序变反），
 *                     前 n-k 个来到后面（顺序也变反）
 *   2. 反转前 k 个  → 纠正前面这 k 个的顺序
 *   3. 反转剩余部分 → 纠正后面 n-k 个的顺序
 *
 * 例: [1,2,3,4,5,6,7], k = 3
 *   反转整个:  [7,6,5,4,3,2,1]
 *   反转前3个: [5,6,7,4,3,2,1]
 *   反转剩余:  [5,6,7,1,2,3,4]  ✓
 *
 * 关键点: 先 k %= n——k 可能大于数组长度，
 *         右转 n 位等于没转，真正有效的是 k % n 位
 *         （例: n = 3, k = 4 等价于 k = 1）
 *
 * 其他解法: ① 新数组直接拷贝 O(n) 空间 ② 环状替换 O(1) 空间
 *          三次反转最简洁，最好记
 *
 * 复杂度: 时间 O(n)（每个元素最多交换两次），空间 O(1)
 */

/**
 * rotate
 * 输入: nums = [1,2,3,4,5,6,7], k = 2
 * @param {number[]} nums
 * @param {number} k
 * @return {void} 原地修改,不返回值
 */
const rotate = function (nums, k) {
  const n = nums.length;
  k %= n; // k 可能大于数组长度，取余后才是真正要转的次数

  // 反转 [start, end] 区间（双指针原地交换）
  const reverse = (start, end) => {
    while (start < end) {
      [nums[start], nums[end]] = [nums[end], nums[start]];
      start++;
      end--;
    }
  };

  debugger

  reverse(0, n - 1); // 1. 反转整个数组
  reverse(0, k - 1); // 2. 反转前 k 个，纠正顺序
  reverse(k, n - 1); // 3. 反转剩余 n-k 个，纠正顺序

  // 原地修改 nums，不返回值
};

