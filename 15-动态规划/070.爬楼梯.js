/**
 * LeetCode 热题 100 —— 动态规划
 *
 * 70. 爬楼梯 (Climbing Stairs)
 * 难度: 简单 | 标签: 记忆化、数学、动态规划
 * 链接: https://leetcode.cn/problems/climbing-stairs/
 *
 * ───────────────────────────────────────────
 * 题目描述:
 *
 * 假设你正在爬楼梯。需要 `n` 阶你才能到达楼顶。
 *
 * 每次你可以爬 `1` 或 `2` 个台阶。你有多少种不同的方法可以爬到楼顶呢？
 *
 * 示例 1：
 *
 *   输入：n = 2
 *   输出：2
 *   解释：有两种方法可以爬到楼顶。
 *   1. 1 阶 + 1 阶
 *   2. 2 阶
 *
 * 示例 2：
 *
 *   输入：n = 3
 *   输出：3
 *   解释：有三种方法可以爬到楼顶。
 *   1. 1 阶 + 1 阶 + 1 阶
 *   2. 1 阶 + 2 阶
 *   3. 2 阶 + 1 阶
 *
 * 提示：
 *   - `1 <= n <= 45`
 */

/**
 * ───────────────────────────────────────────
 * 解题思路: 动态规划 —— 本质就是斐波那契数列
 *
 * ★ 动态规划的思考模板（四步，后面每道 DP 题都按这个来）★
 *
 *   1. 定义状态:  dp[i] 到底表示什么？
 *   2. 转移方程:  dp[i] 能从哪些【更小的状态】推出来？
 *   3. 初始条件:  最小的那几个状态是多少？
 *   4. 返回什么:  答案是哪个 dp 值？
 *
 * 套到这题上:
 *
 *   1. 状态: dp[i] = 爬到第 i 阶的方法数
 *   2. 转移: 想到达第 i 阶，【最后一步】只有两种可能 ——
 *              从第 i-1 阶爬 1 阶上来
 *              从第 i-2 阶爬 2 阶上来
 *            所以   dp[i] = dp[i-1] + dp[i-2]     ← 就是斐波那契
 *   3. 初始: dp[0] = 1（站在地面）、dp[1] = 1
 *   4. 返回: dp[n]
 *
 * 拿 n = 3 走一遍:
 *   dp[0] = 1                         （地面）
 *   dp[1] = 1                         1
 *   dp[2] = dp[1] + dp[0] = 2         1+1 / 2
 *   dp[3] = dp[2] + dp[1] = 3         1+1+1 / 1+2 / 2+1
 *   → 3 ✓
 *
 * ★ dp[0] 为什么是 1（不是 0）★
 *   这是最容易纠结的地方。两种理解都说得通:
 *     - 数列角度: 要让 dp[2] = dp[1] + dp[0] 算出 2（已知 dp[2]=2、
 *       dp[1]=1），那 dp[0] 只能是 1。它是个"让递推式成立的种子值"
 *     - 路径角度: "原地不动"也算一种方案，所以到第 0 阶有 1 种走法
 *   （和 078 子集里"空集也算一个子集"是同一种感觉）
 *
 * ★ 为什么必须用 DP，不能朴素递归 ★
 *
 *   朴素递归写法看着很简洁:
 *     f(n) = f(n-1) + f(n-2)，f(1) = f(2) = 1
 *   但它会把同一个子问题【反复重算】—— f(5) 调用 f(3) 两次、
 *   f(2) 三次…… 计算量是 2^n 级别的。
 *   n = 45 时约 3.5 × 10^13 次调用，必超时。
 *
 *   而 DP 把每个子问题的答案【只算一次、存下来复用】，
 *   复杂度立刻降到 O(n)。这就是动态规划的全部意义:
 *     【用空间换时间，消除重复计算】。
 *
 * 易错点:
 *   1. ★ dp[0] = 1 不能省 ★（见上）
 *   2. 别用朴素递归（会超时）
 *   3. 别用 Binet 通项公式（含浮点开方，n 大了有精度误差）
 *
 * 复杂度:
 *   数组 DP  —— 时间 O(n)，空间 O(n)
 *   滚动变量 —— 时间 O(n)，空间 O(1)   ← 本文件的主解法
 */

/**
 * climbStairsDP
 * 数组 DP: 把状态定义明明白白摆在数组上（最适合理解）
 * 输入: n = 3
 * @param {number} n
 * @return {number}
 */
const climbStairsDP = function (n) {
  // dp[i] = 爬到第 i 阶的方法数
  const dp = new Array(n + 1);
  dp[0] = 1; // ★ 种子值，不能省
  dp[1] = 1;

  for (let i = 2; i <= n; i++) {
    dp[i] = dp[i - 1] + dp[i - 2];
  }

  return dp[n];
};

const jump = (n) => {
  function dp(i) {
    if (i === 0) return 0;
    if (i === 1) return 1;
    if (i === 2) return 2;
    return dp(i -1) + dp(i - 2);
  }
  return dp(3)
}
/**
 * climbStairs
 * 滚动变量: 只留最后两项，空间 O(1)
 * @param {number} n
 * @return {number}
 */
const climbStairs = function (n) {
  // dp[i] 只依赖 dp[i-1] 和 dp[i-2]，再往前那些算完就没用了
  let prev = 1; // dp[0]
  let cur = 1; // dp[1]

  for (let i = 2; i <= n; i++) {
    const next = prev + cur; // dp[i] = dp[i-1] + dp[i-2]
    prev = cur; // 往前滚一格
    cur = next;
  }

  return cur;
};

