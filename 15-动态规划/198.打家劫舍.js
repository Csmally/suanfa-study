/**
 * LeetCode 热题 100 —— 动态规划
 *
 * 198. 打家劫舍 (House Robber)
 * 难度: 中等 | 标签: 数组、动态规划
 * 链接: https://leetcode.cn/problems/house-robber/
 *
 * ───────────────────────────────────────────
 * 题目描述:
 *
 * 你是一个专业的小偷，计划偷窃沿街的房屋。每间房内都藏有一定的现金，影响你偷窃的唯一制约因素就是相邻的房屋装有相互连通的防盗系统，如果两间相邻的房屋在同一晚上被小偷闯入，系统会自动报警。
 *
 * 给定一个代表每个房屋存放金额的非负整数数组，计算你 不触动警报装置的情况下 ，一夜之内能够偷窃到的最高金额。
 *
 * 示例 1：
 *
 *   输入：[1,2,3,1]
 *   输出：4
 *   解释：偷窃 1 号房屋 (金额 = 1) ，然后偷窃 3 号房屋 (金额 = 3)。
 *        偷窃到的最高金额 = 1 + 3 = 4 。
 *
 * 示例 2：
 *
 *   输入：[2,7,9,3,1]
 *   输出：12
 *   解释：偷窃 1 号房屋 (金额 = 2), 偷窃 3 号房屋 (金额 = 9)，接着偷窃 5 号房屋 (金额 = 1)。
 *        偷窃到的最高金额 = 2 + 9 + 1 = 12 。
 *
 * 提示：
 *   - `1 <= nums.length <= 100`
 *   - `0 <= nums[i] <= 400`
 */

/**
 * ───────────────────────────────────────────
 * 解题思路: 动态规划 —— 每间房"偷 or 不偷"
 *
 * ★ 套用 DP 的四步模板 ★
 *
 *   1. 状态: dp[i] = 只考虑 nums[0..i] 这几间房，能偷到的最高金额
 *   2. 转移: 对第 i 间房，只有两个选择 ——
 *              【不偷】→ 最大值就是 dp[i-1]
 *              【偷】  → 第 i-1 间必须空着，所以只能在 0..i-2 里选，
 *                       最大值是 dp[i-2] + nums[i]
 *            所以   dp[i] = max(dp[i-1], dp[i-2] + nums[i])
 *   3. 初始: dp[0] = nums[0]
 *            dp[1] = max(nums[0], nums[1])
 *   4. 返回: dp[n-1]
 *
 * ★ 转移里最关键的一处: 是 dp[i-2]，不是 dp[i-1] ★
 *
 *   "偷了第 i 间"这个决定会【封死第 i-1 间】—— 这才是题目的核心
 *   约束。所以偷 i 的时候，前面能选的只剩 0..i-2。
 *   写成 dp[i-1] + nums[i] 就等于允许偷相邻两间，直接错。
 *
 * 拿 [1, 2, 3, 1] 走一遍:
 *
 *   i   nums[i]   dp[i-1]   dp[i-2]+nums[i]   dp[i]
 *   ──────────────────────────────────────────────────
 *   0   1         -         -                 1
 *   1   2         -         -                 2        max(1, 2)
 *   2   3         2         1 + 3 = 4         4   ★
 *   3   1         4         2 + 1 = 3         4
 *   → 4 ✓（偷第 0 间和第 2 间：1 + 3）
 *
 * ★ 为什么不能用"隔一个偷一个"的贪心 ★
 *
 *   看起来挺有道理（偷 0、跳 1、偷 2、跳 3……），但它【不是最优】。
 *   反例 [2, 1, 1, 2]:
 *     贪心（从 0 开始）: 2 + 1 = 3
 *     贪心（从 1 开始）: 1 + 2 = 3
 *     真正最优:          2 + 2 = 4    ← 连跳过中间两间小的
 *   贪心错在"只看相邻一间"，而最优解可能需要【连跳两间】。
 *   这正是需要 DP 的原因: 得记住"前面所有位置的最优值"，而不是
 *   只记住"上一间偷没偷"。
 *
 * 易错点:
 *   1. ★ 转移里是 dp[i-2]，不是 dp[i-1] ★（见上）
 *   2. ★ 数组版要处理 n === 1 ★
 *      因为要访问 dp[1]，n = 1 时会越界。
 *      用滚动变量版能天然绕开（见下）
 *   3. nums[i] 可以是 0，所以 dp 不能靠"值是否大于 0"来判断偷没偷
 *
 * 复杂度:
 *   数组 DP  —— 时间 O(n)，空间 O(n)
 *   滚动变量 —— 时间 O(n)，空间 O(1)   ← 本文件的主解法
 *
 * ── 滚动变量版有个很漂亮的初始化 ★ ──
 *   令 prev = 0（看作 dp[-2]）、cur = 0（看作 dp[-1]），
 *   这两个"幽灵下标"都表示"还没有房子可偷 = 0"。
 *   这样连 n = 1 都不用特判，循环里一视同仁。
 */

/**
 * rob
 * 滚动变量: 只留前两项，空间 O(1)
 * 输入: nums = [1,2,3,1]
 * @param {number[]} nums
 * @return {number}
 */
const rob = function (nums) {
  let prev = 0; // 看作 dp[i-2]，初始是"没房子"= 0
  let cur = 0; // 看作 dp[i-1]，初始也是"没房子"= 0

  for (const v of nums) {
    // dp[i] = max(不偷: dp[i-1], 偷: dp[i-2] + nums[i])
    const next = Math.max(cur, prev + v);

    prev = cur; // 往前滚一格
    cur = next;
  }

  return cur;
};

/**
 * robDP
 * 数组 DP: 把状态定义明明白白摆在数组上
 * @param {number[]} nums
 * @return {number}
 */
const robDP = function (nums) {
  const n = nums.length;
  if (n === 1) return nums[0]; // ★ 必须特判，否则下面 dp[1] 越界

  const dp = new Array(n);
  dp[0] = nums[0];
  dp[1] = Math.max(nums[0], nums[1]);

  for (let i = 2; i < n; i++) {
    dp[i] = Math.max(dp[i - 1], dp[i - 2] + nums[i]);
  }

  return dp[n - 1];
};

