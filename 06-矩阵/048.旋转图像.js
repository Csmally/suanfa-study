/**
 * ───────────────────────────────────────────
 * 解题思路: 转置 + 每行反转（两步组合 = 顺时针旋转 90°）
 *
 * 顺时针旋转 90° 的目标: 元素 (i, j) 移动到 (j, n-1-i)
 * 把这一步拆成两个简单操作:
 *   1. 转置（沿主对角线翻转）: (i, j) → (j, i)
 *      只遍历对角线"上方的三角形"（j 从 i+1 开始），
 *      否则每对元素会被交换两次又换回去
 *   2. 每行左右反转: (j, i) → (j, n-1-i)
 * 两步合起来正好是顺时针旋转 90°（证明: 目标位置一致）
 *
 * 例: [[1,2,3],[4,5,6],[7,8,9]]
 *   转置:     [[1,4,7],[2,5,8],[3,6,9]]
 *   每行反转: [[7,4,1],[8,5,2],[9,6,3]] ✓
 *
 * 另一个思路: 四格轮换法——一圈一圈处理，每圈的四个角同时交换，
 *   同样 O(1) 空间，但边界更容易写错；转置+反转最好记
 *
 * 复杂度: 时间 O(n²)，空间 O(1)（原地修改）
 */

/**
 * rotate
 * 输入: matrix = [[1,2,3],[4,5,6],[7,8,9]]
 * @param {number[][]} matrix
 * @return {void} 原地修改,不返回值
 */
const rotate = function (matrix) {
  const n = matrix.length;

  
  // 1. 转置: 沿主对角线翻转，交换 matrix[i][j] 和 matrix[j][i]
  //    j 从 i + 1 开始 → 只处理对角线上方的三角形
  for (let i = 0; i < n; i++) {
    for (let j = i + 1; j < n; j++) {
      [matrix[i][j], matrix[j][i]] = [matrix[j][i], matrix[i][j]];
    }
  }
  debugger

  // 2. 每行左右反转
  for (let i = 0; i < n; i++) {
    matrix[i].reverse();
  }

  // 原地修改 matrix，不返回值
};

