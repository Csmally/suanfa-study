/**
 * LeetCode 热题 100 —— 技巧
 *
 * 75. 颜色分类 (Sort Colors)
 * 难度: 中等 | 标签: 数组、双指针、冒泡排序、排序、快速排序
 * 链接: https://leetcode.cn/problems/sort-colors/
 *
 * ───────────────────────────────────────────
 * 题目描述:
 *
 * 给定一个包含红色、白色和蓝色、共 `n` 个元素的数组 `nums` ，原地 对它们进行排序，使得相同颜色的元素相邻，并按照红色、白色、蓝色顺序排列。
 *
 * 我们使用整数 0、 1 和 2 分别表示红色、白色和蓝色。
 *
 * 必须在不使用库内置的 sort 函数的情况下解决这个问题。
 *
 * 示例 1：
 *
 * 输入：nums = [2,0,2,1,1,0]
 *
 * 输出：[0,0,1,1,2,2]
 *
 * 解释：
 *
 * 该数组包含两个 0、两个 1 和两个 2。将它们原地排序后，所有 0 排在最前面，接着是所有 1，最后是所有 2。
 *
 * 示例 2：
 *
 * 输入：nums = [2,0,1]
 *
 * 输出：[0,1,2]
 *
 * 解释：
 *
 * 数组中有且仅有一个 0、一个 1 和一个 2，按 0、1、2 的顺序原地排列。
 *
 * 提示：
 *   - `n == nums.length`
 *   - `1 <= n <= 300`
 *   - `nums[i]` 为 0、1 或 2
 *
 * 进阶：
 *   - 你能想出一个仅使用常数空间的一趟扫描算法吗？
 */

/**
 * ───────────────────────────────────────────
 * 解题思路: 荷兰国旗问题 —— 三指针一趟扫描
 *
 * ★ 这题为什么叫"荷兰国旗"★
 *   荷兰国旗就是红白蓝三条横杠，正好对应 0 / 1 / 2 三个分区。
 *   这是 Dijkstra 提出的经典问题，也是快速排序里【三路切分】的原型。
 *
 * ★ 核心想法: 把数组划成四段，用一个指针 i 往前走 ★
 *
 *     0 0 0 | 1 1 1 | ? ? ? ? | 2 2 2
 *           ↑       ↑         ↑
 *          low     i        high
 *
 *   四个区间（注意边界是开是闭）:
 *     [0, low)     已确定的【0 区】
 *     [low, i)     已确定的【1 区】
 *     [i, high]    【还没看过】的未知区   ← 工作区
 *     (high, n-1]  已确定的【2 区】
 *
 *   每轮只看 nums[i] 是几:
 *     = 0 → 和 nums[low] 交换，然后 low++、i++
 *     = 1 → 不动，i++（1 本来就该在中间，待在原地就行）
 *     = 2 → 和 nums[high] 交换，然后 high--，★ i 不动 ★
 *
 * ★ 最关键的一点: 换 2 的时候【不能】i++ ★
 *
 *   因为从 high 那边换过来的元素【根本还没被检查过】，它可能是 0、1 或 2，
 *   必须留在原地下一轮接着看。如果手快写了 i++，那个元素就被跳过了，答案就错。
 *
 *   那为什么换 0 的时候 i++ 是安全的？想清楚这一点才算真懂:
 *     注意 low <= i 恒成立。
 *       · 若 low === i: 自己和自己换，什么都没发生，i++ 当然没问题。
 *       · 若 low < i:  区间 [low, i) 里的元素全都是 1，所以 nums[low] 必然是 1。
 *                     换完之后，位置 i 上放着的就是一个 1 ——
 *                     而 1 本来就属于中间那段，不用再挪了，跳过它是正确的。
 *
 * ★ 循环条件为什么是 i <= high 而不是 i < n ★
 *   high 右边那一截已经是确定好的 2 区了，不用再看。i 只要越过 high 就说明
 *   未知区已经空掉，此时数组自然就是 [0区][1区][2区]，完事。
 *
 * 拿示例 1  [2,0,2,1,1,0] 走一遍:
 *
 *   初始: low=0, i=0, high=5      [2, 0, 2, 1, 1, 0]
 *
 *   ① nums[0]=2 → 和 nums[5] 换, high=4, i 不动
 *      [0, 0, 2, 1, 1, 2]   low=0, i=0, high=4
 *   ② nums[0]=0 → 和自己换(low===i), low=1, i=1
 *      [0, 0, 2, 1, 1, 2]   low=1, i=1, high=4
 *   ③ nums[1]=0 → 和自己换(low===i), low=2, i=2
 *   ④ nums[2]=2 → 和 nums[4] 换, high=3, i 不动
 *      [0, 0, 1, 1, 2, 2]   low=2, i=2, high=3
 *   ⑤ nums[2]=1 → i=3
 *   ⑥ nums[3]=1 → i=4
 *   ⑦ i=4 > high=3 → 结束
 *
 *   → [0, 0, 1, 1, 2, 2] ✓
 *
 * ★ 它和快速排序是什么关系 ★
 *
 *   快排的【两路切分】把数组分成 "< pivot" 和 ">= pivot" 两堆。
 *   当数组里有大量重复元素时，两路切分等于 pivot 的那些元素还会被反复比较、来回搬。
 *
 *   【三路切分】把数组分成 "< pivot | == pivot | > pivot" 三堆，
 *   等于 pivot 的元素一次性放到最终位置，再也不参与后续递归 —— 效率高得多。
 *
 *   这题就是"三路切分"的一个特例: pivot 恰好只可能是 0、1、2 这三个值，
 *   等于 pivot 的那一堆就是中间的 1 区，扫一遍就全部归位了。
 *   ★ 所以学会这题，等于拿到了快排三路切分的全部思路 ★
 *
 * ★ 其他解法 ★
 *
 *   解法              循环次数   空间     说明
 *   ──────────────────────────────────────────────────────────────
 *   三指针(荷兰国旗)  一趟       O(1)     ★ 满足进阶要求 ★
 *   计数排序          两趟       O(1)     先数各自几个，再回填，代码更简单
 *   内置 sort         —          —        题目明令禁止
 *   冒泡/选择          O(n²)      O(1)    标签里有，但这题用它纯属绕远路
 *
 *   计数排序版虽然要扫两趟，但常数极小、代码短，在 n 只有 300 的本题里
 *   实际跑起来未必比三指针慢。两种都值得会。
 *
 * 易错点:
 *   1. ★ 换 2 之后 i 不能往前走 ★（原因见上，这是全题唯一的真陷阱）
 *   2. 循环条件是 i <= high，不是 i < n
 *   3. 换 0 之后 low 和 i 都要 ++，两个都别忘了
 *   4. ★ JS 里用解构赋值交换两个元素时，行首要小心分号 ★
 *        上一行末尾如果没写分号，而这一行以 `[` 开头，
 *        JS 的自动分号插入(ASI)会把两行连起来解析。实测过，它会【静默出错】:
 *
 *          const tmp = nums[low]
 *          [nums[low], nums[i]] = [nums[i], nums[low]]     ← 忘了分号
 *
 *        上面两行会被解析成一句:
 *          const tmp = nums[low][nums[low], nums[i]] = [nums[i], nums[low]]
 *        结果是【不报错】，但 nums【一点都没变】，而 tmp 被赋成了 `[3, 1]` 这种垃圾值。
 *        这种"没报错但结果不对"的 bug 最难查。
 *
 *        两个稳妥写法，二选一:
 *          · 行首加个分号: `;[nums[low], nums[i]] = [nums[i], nums[low]]`
 *          · 或者干脆用临时变量换（本文件就是这么写的，彻底绕开这个问题）
 *
 *      ★ 顺便说，本项目里已经出现过一次这个坑 —— 写压力测试造数组时，
 *        以 `;[big[i], big[j]] = ...` 开头就是为了防它 ★
 *
 * 复杂度:
 *   三指针 —— 时间 O(n)，空间 O(1)   ← 主解法
 *   计数排序 —— 时间 O(n)（正好两趟），空间 O(1)
 *
 *   ★ 三指针的循环体【精确地跑 n 次】★（实测验证过，不是"大约"）
 *   因为每轮必然执行 i++ 或 high-- 中的恰好一个，所以 high - i 每轮减少 1。
 *   一开始 high - i = n - 1，循环在 i > high（即 high - i = -1）时停止，
 *   于是轮数 = (n-1) - (-1) = n。正好一趟，一个不多一个不少。
 */

/**
 * sortColors
 * 荷兰国旗三指针: 一趟扫描 + 常数空间 —— 本文件主解法
 * @param {number[]} nums
 * @return {void} 原地修改，不返回值
 */
const sortColors = function (nums) {
  let low = 0; // 0 区的右边界: 下一个 0 应该放到这儿
  let i = 0; // 正在检查的元素
  let high = nums.length - 1; // 2 区的左边界: 下一个 2 应该放到这儿

  while (i <= high) {
    if (nums[i] === 0) {
      // 甩到前面去。换过来的要么是它自己(低位指针重合)，要么是个 1 —— 所以 i 可以往前走
      const tmp = nums[low];
      nums[low] = nums[i];
      nums[i] = tmp;
      low++;
      i++;
    } else if (nums[i] === 1) {
      // 1 本来就该待在中间那段，什么都不用做
      i++;
    } else {
      // nums[i] === 2: 甩到后面去
      const tmp = nums[high];
      nums[high] = nums[i];
      nums[i] = tmp;
      high--;
      // ★ 这里【不写 i++】—— 换过来的那个元素还没检查过，下一轮还得看它 ★
    }
  }
};

/**
 * sortColorsCount
 * 计数排序: 先数一遍 0/1/2 各有几个，再按要求回填。两趟，但代码更短
 * 进阶要求"一趟扫描"，所以这个不达标 —— 但它是个很好的对照
 * @param {number[]} nums
 * @return {void} 原地修改，不返回值
 */
const sortColorsCount = function (nums) {
  const count = [0, 0, 0];

  // 第一趟: 数数
  for (const x of nums) count[x]++;

  // 第二趟: 按 0、1、2 的顺序把数组填回去
  let idx = 0;
  for (let value = 0; value <= 2; value++) {
    for (let k = 0; k < count[value]; k++) {
      nums[idx] = value;
      idx++;
    }
  }
};

/**
 * sortColorsBrute
 * 参照实现: 冒泡排序，O(n²)，只用来对答案
 * （题目禁止用内置 sort，所以这里手写一个最朴素的排序当参照）
 * @param {number[]} nums
 * @return {void} 原地修改，不返回值
 */
const sortColorsBrute = function (nums) {
  const n = nums.length;

  for (let i = 0; i < n - 1; i++) {
    for (let j = 0; j < n - 1 - i; j++) {
      if (nums[j] > nums[j + 1]) {
        const tmp = nums[j];
        nums[j] = nums[j + 1];
        nums[j + 1] = tmp;
      }
    }
  }
};

